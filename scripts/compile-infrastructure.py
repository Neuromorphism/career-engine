#!/usr/bin/env python3
"""Validate the infrastructure dependency DAG and compile buildless browser data."""
import argparse, hashlib, json, tomllib, math
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def compile_infrastructure():
    raw = (ROOT/'data/infrastructure.toml').read_bytes()
    data = tomllib.loads(raw.decode())
    careers = tomllib.loads((ROOT/'data/careers.toml').read_text())
    roles = {n['id'] for n in careers['nodes'] if n['kind']=='occupation'}
    elements = {e['id']:e for e in data['elements']}
    if len(elements)!=len(data['elements']): raise ValueError('Duplicate infrastructure ID')
    visited, visiting = set(), set()
    def visit(id):
        if id in visiting: raise ValueError('Infrastructure dependency cycle')
        if id in visited: return
        if id not in elements: raise ValueError('Unknown infrastructure dependency')
        visiting.add(id)
        for dep in elements[id]['requires']: visit(dep)
        visiting.remove(id); visited.add(id)
    for id,e in elements.items():
        visit(id)
        for field in ['profession_groups','maintenance_groups']:
            if not e[field] or any(not group or set(group)-roles for group in e[field]):
                raise ValueError('Empty or unknown profession group')
    sources = {s['id'] for s in data['sources']}
    seen=set()
    for o in data['observations']:
        key=(o['element'],o['year'])
        if key in seen or o['element'] not in elements or o['source'] not in sources or not 0<=o['coverage']<=1:
            raise ValueError('Invalid historical observation')
        seen.add(key)
    if data['version']!=1 or data['coverage_per_unlock']!=1: raise ValueError('Unsupported infrastructure rules')
    # Fit descriptive logistic adoption on 1940–1970; reserve 1980/1990 for scoring.
    train=[o for o in data['observations'] if o['element']=='plumbing' and o['year']<=1970]
    xs=[o['year']-1940 for o in train]
    ys=[math.log(o['coverage']/(1-o['coverage'])) for o in train]
    mx=sum(xs)/len(xs); my=sum(ys)/len(ys)
    slope=sum((x-mx)*(y-my) for x,y in zip(xs,ys))/sum((x-mx)**2 for x in xs)
    intercept=my-slope*mx
    predict=lambda year: 1/(1+math.exp(-(intercept+slope*(year-1940))))
    scores=[{'year':o['year'],'observed':o['coverage'],'predicted':predict(o['year']),
             'absoluteErrorPP':100*abs(predict(o['year'])-o['coverage'])}
            for o in data['observations'] if o['element']=='plumbing' and o['year']>1970]
    data['adoptionFit']={'element':'plumbing','origin':1940,'intercept':intercept,'slope':slope,
                         'trainingYears':[o['year'] for o in train],'holdout':scores,
                         'holdoutMaePP':sum(s['absoluteErrorPP'] for s in scores)/len(scores),
                         'status':'descriptive national adoption; does not identify profession effects'}
    return '// Generated by scripts/compile-infrastructure.py; do not edit.\nexport const infrastructureData = '+json.dumps({**data,'sourceHash':hashlib.sha256(raw).hexdigest()},indent=2)+';\n'
if __name__=='__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    content=compile_infrastructure(); target=ROOT/'world-infra/infrastructure-data.js'
    if args.check:
        if not target.exists() or target.read_text()!=content: raise ValueError('Infrastructure artifact stale; run npm run compile')
    else: target.write_text(content)
    print('Infrastructure definitions, professions, historical observations and dependency graph valid.')
