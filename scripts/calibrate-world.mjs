import { readFileSync, writeFileSync } from 'node:fs';
import { metroData } from '../real-world/metro-data.js';
import { evaluateMetros, fitMetro, predictMetro } from './lib/calibration.js';
import { TREND_STRUCTURE } from '../src/world-models/inference.js';
import { createWorld } from '../world/world-engine.js';
import { workforceExperiment } from '../src/world-models/professions.js';
const evaluation=evaluateMetros(metroData.metros);
let seed=20261014;
const random=()=>{seed=(Math.imul(seed,1664525)+1013904223)>>>0;return (seed+.5)/4294967296;};
const normal=()=>Math.sqrt(-2*Math.log(random()))*Math.cos(2*Math.PI*random());
const simulations=[];
for (const metro of metroData.metros) {
  const fit=fitMetro(metro);
  for (const year of [2017,2018,2019]) {
    const estimate=predictMetro(fit,year);
    const samples=Array.from({length:200},()=>estimate.gdp*Math.exp(normal()*fit.fits.gdp.innovation*Math.sqrt(year-2016))).sort((a,b)=>a-b);
    const mixes=[];
    for (const [name,allocations] of Object.entries({unclassified:{},clinical:{'registered-nurse':10000,'family-medicine-physician':5000},education:{'elementary-teacher':15000},infrastructure:{carpenter:5000,'commercial-electrician':5000,'service-plumber':5000}})) {
      const world={...createWorld(),allocations,productivityMultiplier:1};
      const metrics={experiment:workforceExperiment(world,estimate.employed,estimate.population)};
      mixes.push({name,allocatedWorkers:metrics.experiment.assigned,outputFactor:metrics.experiment.outputFactor,
        serviceIndices:metrics.experiment.services.map(s=>({id:s.id,index:s.index})),validated:false});
    }
    simulations.push({metroId:metro.id,year,gdp:estimate.gdp,trainingInnovationRange95:[samples[4],samples[195]],mixes});
  }
}
const result={...evaluation, source:metroData.source, seed:20261014,
  selectionNote:'Initial panel: ten cities including Madrid. Amsterdam added after Madrid failed, retaining Madrid. City selection is adaptive; this is not an unbiased ten-city success estimate.',
  limits:['Historical secondary-source benchmarks, not current-world forecasts.','Occupation-mix effects are not trained: no matching observed occupation panel was acquired.','GDP/head and output/employed are arithmetic derivatives, not independent validations.','Simulation ranges use training innovations and are not calibrated coverage guarantees.'],
  simulationCount:simulations.length*200,simulations,
  fittedModels:metroData.metros.map(m=>fitMetro(m)),
};
const artifact={
  schemaVersion:1, modelId:'real-world', modelVersion:1, sourceHash:metroData.source.sha256,
  trainingStart:2010, trainingEnd:2016, simulationEnd:2019,
  structure:TREND_STRUCTURE, fittedModels:result.fittedModels,
  validation:{...evaluation,cities:evaluation.cities.map(({points,...summary})=>summary)},
};
const outputs=[
  [new URL('../data/real-world/calibration-report.json',import.meta.url),JSON.stringify(result,null,2)+'\n'],
  [new URL('../real-world/model-data.js',import.meta.url),'// Generated by scripts/calibrate-world.mjs. Data only; do not edit.\nexport const worldModelData = '+JSON.stringify(artifact,null,2)+';\n'],
];
for (const [path,content] of outputs) {
  if(process.argv.includes('--check')) {
    if(readFileSync(path,'utf8')!==content) throw new Error(`Generated artifact is stale: ${path.pathname}. Run node scripts/calibrate-world.mjs.`);
  } else writeFileSync(path,content);
}
console.log(`${result.passed}/${result.total} metros pass historical baseline criteria; ${result.simulationCount} seeded GDP draws and ${simulations.length*4} workforce scenarios. Profession effects: unvalidated.`);
