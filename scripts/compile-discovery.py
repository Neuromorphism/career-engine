#!/usr/bin/env python3
"""Compile the browse graph independently of training prerequisites."""
import argparse,hashlib,json,tomllib
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def compile_discovery():
 raw=(ROOT/'data/discovery.json').read_bytes();data=json.loads(raw)
 careers=tomllib.loads((ROOT/'data/careers.toml').read_text())
 ids={n['id'] for n in careers['nodes'] if n['kind']=='occupation'}
 categories={c['id']:c for c in data['categories']}
 if len(categories)!=len(data['categories']):raise ValueError('Duplicate browse category')
 paths={(c['id'],f['id']) for c in data['categories'] for f in c['families']}
 if len(paths)!=sum(len(c['families']) for c in data['categories']):raise ValueError('Duplicate browse family')
 seen=set()
 for role in data['professions']:
  if role['id'] in seen or role['id'] not in ids:raise ValueError('Unknown or duplicate canonical profession')
  seen.add(role['id'])
  if not role['label'].strip():raise ValueError('Missing profession display title')
  links=[role['primary']]+role['also_found_under']
  if len({(p['category_id'],p['family_id']) for p in links})!=len(links):raise ValueError('Duplicate browse path')
  for path in links:
   if (path['category_id'],path['family_id']) not in paths:raise ValueError('Unknown browse path')
  if any(not isinstance(term,str) or not term.strip() for term in role['search_terms']):raise ValueError('Invalid search term')
 if seen!=ids:raise ValueError('Every playable profession must have exactly one primary browse record')
 for route in data['search_routes']:
  if set(route['role_ids'])-ids:raise ValueError('Unknown search suggestion')
 return '// Generated by scripts/compile-discovery.py; do not edit.\n// Source SHA-256: '+hashlib.sha256(raw).hexdigest()+'\nexport const discoveryData = '+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n'
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
 text=compile_discovery();target=ROOT/'src/discovery-data.js'
 if args.check:
  if not target.exists() or target.read_text()!=text:raise ValueError('Discovery artifact stale; run npm run compile')
 else:target.write_text(text)
 print('Discovery graph valid: unique professions, complete coverage, valid cross-links.')
