"""Compile archived observations without filling missing cells or mixing geographies."""
import argparse
import csv
import hashlib
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / 'data/real-world/raw/pre-imputation.csv'
CITIES = [
 ('london','United Kingdom','London'), ('paris','France','Paris'),
 ('berlin','Germany','Berlin'), ('madrid','Spain','Madrid'),
 ('tokyo','Japan','Tokyo'), ('seoul','Korea','Seoul'),
 ('sydney','Australia','Greater Sydney'), ('toronto','Canada','Toronto'),
 ('mexico-city','Mexico','Mexico City'), ('santiago','Chile','Santiago'),
 ('amsterdam','Netherlands','Amsterdam')]
METRICS = {
 'population': ('Population, all ages, administrative data', 'people'),
 'labourForce': ('Labour force (15-64 years old)', 'people aged 15–64'),
 'unemployment': ('Unemployment rate (unemployment 15-64 over labour force 15-64)', '% of labour force aged 15–64'),
 'gdp': ('GDP (Million USD, constant prices, constant PPP, base year 2015)', 'million USD, constant 2015 prices and PPP'),
 'density': ('Population density (inhabitants per km²)', 'people/km²'),
 'pm25': ('Mean population exposure to PM2.5 air pollution', 'µg/m³'),
}
rows = list(csv.DictReader(RAW.open()))
metros = []
for id, country, city in CITIES:
 selected = {}
 for key, (variable, _) in METRICS.items():
  matches = [r for r in rows if (r['country'],r['city'],r['variable']) == (country, city, variable)]
  if len(matches) != 1: raise ValueError(f'Ambiguous or missing {city}/{key}')
  selected[key] = matches[0]
 observations = []
 for year in range(2009,2020):
  record = {'year': year}
  for key, row in selected.items():
   cell = row[str(year)]
   record[key] = None if cell in ('','NA') else float(cell)
  observations.append(record)
 metros.append({'id':id, 'name':city, 'country':country, 'geography':'OECD functional urban area as archived; not city proper', 'observations':observations})
data = {
 'schemaVersion':1,
 'source': {
  'title':'OECD City Statistics, archived by Marco Di Maio and Pasquale Somma',
  'upstream':'https://www.oecd.org/en/data/datasets/oecd-definition-of-cities-and-functional-urban-areas.html',
  'url':'https://github.com/Marco210210/City-Statistics-OECD-FUA-Analysis/blob/17162d21c78016d7af31fed4553ebfcd64621013/dataset/intermediate/Clean_dataset_with_NA.csv',
  'commit':'17162d21c78016d7af31fed4553ebfcd64621013',
  'sha256':hashlib.sha256(RAW.read_bytes()).hexdigest(),
  'retrieved':'2026-10-14', 'coverage':'2009–2019; historical, not current estimates',
  'license':'Mirror: CC BY-NC-SA 4.0. Attribution and noncommercial/share-alike conditions apply to this data adaptation.',
  'quality':'Secondary archive, before its interpolation step. Original OECD API values and historical FUA boundary vintages have not been independently reverified. No missing cells are imputed here.',
 },
 'metrics':{k:{'sourceLabel':v,'unit':u} for k,(v,u) in METRICS.items()},
 'metros':metros,
}
content = '// Generated by scripts/compile-metros.py; do not edit.\nexport const metroData = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
target = ROOT / 'real-world/metro-data.js'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
if parser.parse_args().check:
 if not target.exists() or target.read_text() != content: raise SystemExit('Metro data is stale: run npm run compile')
else:
 target.write_text(content)
print(f'Checked {len(metros)} metros, {sum(len(m["observations"]) for m in metros)} annual snapshots; missing values preserved.')
